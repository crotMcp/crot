function ico(entries) {
  const header = Buffer.alloc(6 + 16 * entries.length);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(entries.length, 4);
  let offset = header.length;
  entries.forEach(([size, b], i) => {
    const n = 6 + 16 * i;
    header[n] = size === 256 ? 0 : size;
    header[n + 1] = header[n];
    header.writeUInt16LE(1, n + 4);
    header.writeUInt16LE(32, n + 6);
    header.writeUInt32LE(b.length, n + 8);
    header.writeUInt32LE(offset, n + 12);
    offset += b.length;
  });
  return Buffer.concat([header, ...entries.map((e) => e[1])]);
}
