let fonts = "";
for (const name of ["inter", "jetbrains-mono"]) {
  let css = await read(`node_modules/@fontsource-variable/${name}/wght.css`);
  const blocks = css.match(/\/\*[^]*?\}/g) || [];
  for (let block of blocks) {
    if (!/-((cyrillic|latin)(-ext)?)-wght-normal/.test(block)) continue;
    const file = /url\(\.\/([^)]*)\)/.exec(block)?.[1];
    if (!file) throw new Error("Font path");
    const b = await readFile(new URL(`node_modules/@fontsource-variable/${name}/${file}`, root));
    block = block
      .replace(/url\([^)]*\)/, `url(data:font/woff2;base64,${b.toString("base64")})`)
      .replace("font-display: swap", "font-display: block");
    fonts += block + "\n";
  }
}
